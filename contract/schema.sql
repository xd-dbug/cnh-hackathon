-- Contract v2: the Postgres schema. Owned by D. Agents read it but never edit it.
-- The worker writes conferences and talks; the API reads them and inserts queued conferences.
-- pg-boss keeps its queue tables in its own `pgboss` schema, which it creates itself.
-- Re-running this file is safe.

CREATE EXTENSION IF NOT EXISTS vector;

-- array_to_string is only STABLE, and a generated column needs IMMUTABLE expressions.
-- It is safe here because text[] output never depends on settings.
CREATE OR REPLACE FUNCTION text_array_join(text[]) RETURNS text
  LANGUAGE sql IMMUTABLE PARALLEL SAFE
  RETURN array_to_string($1, ' ');

CREATE TABLE IF NOT EXISTS conferences (
  id          text PRIMARY KEY CHECK (id ~ '^[a-z0-9]{10}$'),  -- generated by the API
  source_url  text NOT NULL UNIQUE,  -- normalised, see contract/README.md
  platform    text CHECK (platform IN ('sessionize', 'pretalx', 'frab', 'sched', 'ical', 'jsonld')),
  name        text,                  -- set by the worker once parsed
  timezone    text,                  -- IANA name, e.g. America/Denver
  status      text NOT NULL DEFAULT 'queued'
              CHECK (status IN ('queued', 'fetching', 'parsing', 'embedding', 'ready', 'failed')),
  error       text,                  -- set only when status = 'failed'
  talk_count  integer CHECK (talk_count >= 0),
  created_at  timestamptz NOT NULL DEFAULT now(),
  scraped_at  timestamptz,           -- when the talks were last replaced
  CHECK ((status = 'failed') = (error IS NOT NULL)),
  CHECK (status <> 'ready' OR (name IS NOT NULL AND timezone IS NOT NULL AND talk_count IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS talks (
  conference_id text NOT NULL REFERENCES conferences (id) ON DELETE CASCADE,
  -- COLLATE "C" so ORDER BY id matches JavaScript's default string comparison.
  id         text COLLATE "C" NOT NULL CHECK (id ~ '^[A-Za-z0-9_-]{1,64}$'),
  title      text NOT NULL,
  abstract   text,
  url        text,                   -- the talk's official page, when the source has one
  start_at   timestamptz NOT NULL,
  end_at     timestamptz NOT NULL CHECK (end_at >= start_at),
  room       text,
  venue      text,
  speakers   text[] NOT NULL DEFAULT '{}',
  track      text,
  level      text,
  tags       text[] NOT NULL DEFAULT '{}',
  tsv tsvector GENERATED ALWAYS AS (
    setweight(to_tsvector('english', title), 'A') ||
    setweight(to_tsvector('english', text_array_join(speakers) || ' ' || text_array_join(tags)), 'B') ||
    setweight(to_tsvector('english', coalesce(abstract, '')), 'C')
  ) STORED,
  embedding  vector(384),            -- bge-small-en-v1.5 of title + abstract, normalised
  PRIMARY KEY (conference_id, id)
);

CREATE INDEX IF NOT EXISTS talks_by_time ON talks (conference_id, start_at, id);
CREATE INDEX IF NOT EXISTS talks_tsv ON talks USING gin (tsv);
CREATE INDEX IF NOT EXISTS talks_embedding ON talks USING hnsw (embedding vector_cosine_ops);
